create table if not exists tallas (
  id integer generated by default as identity primary key,
  nombre text not null unique,
  orden integer not null default 0,
  activa boolean not null default true
);

create table if not exists colecciones (
  id integer generated by default as identity primary key,
  slug text not null unique,
  nombre text not null,
  descripcion text not null default '',
  temporada text not null default '',
  imagen_url text not null default '',
  activa boolean not null default true,
  destacada boolean not null default false,
  orden integer not null default 0
);

create table if not exists productos (
  id integer generated by default as identity primary key,
  slug text not null unique,
  nombre text not null,
  descripcion text not null default '',
  precio integer not null check (precio >= 0),
  categoria text not null,
  coleccion_id integer references colecciones(id) on delete set null,
  imagen_url text not null default '',
  agotado boolean not null default false,
  activo boolean not null default true,
  orden integer not null default 0,
  creado_en timestamptz not null default now()
);

create table if not exists producto_tallas (
  producto_id integer not null references productos(id) on delete cascade,
  talla_id integer not null references tallas(id) on delete cascade,
  agotado boolean not null default false,
  stock integer not null default 0 check (stock >= 0),
  primary key (producto_id, talla_id)
);

create table if not exists producto_medios (
  id integer generated by default as identity primary key,
  producto_id integer not null references productos(id) on delete cascade,
  tipo text not null check (tipo in ('imagen', 'video')),
  url text not null,
  alt text not null default '',
  orden integer not null default 0
);

create table if not exists carrusel_slides (
  id integer generated by default as identity primary key,
  tipo text not null check (tipo in ('imagen', 'video')),
  url text not null,
  url_movil text,
  titulo text not null default '',
  subtitulo text not null default '',
  texto_boton text not null default '',
  enlace text not null default '/',
  orden integer not null default 0,
  activo boolean not null default true
);

create table if not exists guia_tallas (
  id smallint primary key default 1 check (id = 1),
  titulo text not null default 'Guía de tallas',
  columnas jsonb not null default '[]'::jsonb,
  filas jsonb not null default '[]'::jsonb,
  notas text not null default ''
);

create table if not exists configuracion (
  id smallint primary key default 1 check (id = 1),
  whatsapp text not null,
  texto_anuncio text not null default ''
);

create table if not exists descuentos (
  id integer generated by default as identity primary key,
  nombre text not null,
  porcentaje integer not null check (porcentaje between 1 and 100),
  fecha_vencimiento date not null,
  activo boolean not null default true
);

create table if not exists descuento_productos (
  descuento_id integer not null references descuentos(id) on delete cascade,
  producto_id integer not null references productos(id) on delete cascade,
  primary key (descuento_id, producto_id)
);

create table if not exists descuento_colecciones (
  descuento_id integer not null references descuentos(id) on delete cascade,
  coleccion_id integer not null references colecciones(id) on delete cascade,
  primary key (descuento_id, coleccion_id)
);

create table if not exists codigos_promo (
  id integer generated by default as identity primary key,
  codigo text not null unique,
  porcentaje integer not null check (porcentaje between 1 and 100),
  fecha_vencimiento date,
  usos_maximos integer check (usos_maximos is null or usos_maximos > 0),
  usos integer not null default 0 check (usos >= 0),
  monto_minimo integer check (monto_minimo is null or monto_minimo >= 0),
  activo boolean not null default true
);

create table if not exists pedidos (
  id integer generated by default as identity primary key,
  referencia text not null unique,
  estado text not null default 'pendiente_pago'
    check (estado in ('pendiente_pago', 'pagado', 'enviado', 'entregado', 'cancelado')),
  metodo_pago text not null check (metodo_pago in ('wompi', 'whatsapp')),
  referencia_pago text,
  cliente_nombre text not null,
  cliente_telefono text not null,
  cliente_email text not null,
  envio_departamento text not null,
  envio_ciudad text not null,
  envio_direccion text not null,
  envio_barrio text not null default '',
  envio_notas text not null default '',
  subtotal integer not null check (subtotal >= 0),
  descuento_total integer not null default 0 check (descuento_total >= 0),
  codigo_promo text,
  costo_envio integer not null default 0 check (costo_envio >= 0),
  total integer not null check (total >= 0),
  creado_en timestamptz not null default now(),
  pagado_en timestamptz
);

create table if not exists pedido_items (
  id integer generated by default as identity primary key,
  pedido_id integer not null references pedidos(id) on delete cascade,
  producto_id integer references productos(id) on delete set null,
  slug text not null,
  nombre text not null,
  imagen text not null default '',
  talla text not null,
  cantidad integer not null check (cantidad > 0),
  precio_unitario integer not null check (precio_unitario >= 0),
  descuento_porcentaje integer not null default 0,
  subtotal integer not null check (subtotal >= 0)
);

